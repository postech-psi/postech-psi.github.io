const assert=require('node:assert/strict');
const {chromium}=require('playwright');
const base=process.env.PSI_URL||'http://127.0.0.1:8767';
async function checkReel(browser){
 for(const locale of ['', 'ko/']){
  const context=await browser.newContext({viewport:{width:1440,height:1000}});
  const page=await context.newPage();
  await page.clock.install();
  await page.goto(`${base}/${locale}index.html`);
  const reel=page.locator('[data-photo-reel]');
  assert.equal(await reel.count(),1,'A real photo reel is present');
  await reel.scrollIntoViewIfNeeded();await page.waitForTimeout(150);
  await page.clock.pauseAt(new Date(Date.now()+1000));
  await reel.hover();await page.mouse.move(0,0);
  const selected=()=>reel.locator('[data-reel-slide]:visible').getAttribute('data-reel-slide');
  const firstBox=await reel.boundingBox();
  assert.equal(await selected(),'0');
  await page.clock.runFor(6999);assert.equal(await selected(),'0');
  await page.clock.runFor(2);assert.equal(await selected(),'1');
  assert.ok(await page.locator('[data-flight-video]').evaluate(v=>v.paused),'Visible reel stops background movie');
  await reel.locator('[data-reel-next]').click();assert.equal(await selected(),'2');
  await page.clock.runFor(15000);assert.equal(await selected(),'2','Focus pauses autoplay');
  await reel.locator('[data-reel-prev]').click();assert.equal(await selected(),'1');
  await reel.locator('[data-reel-dot="3"]').click();assert.equal(await selected(),'3');
  await page.keyboard.press('ArrowRight');assert.equal(await selected(),'0');
  await reel.locator('[data-reel-toggle]').click();
  await page.locator('[data-program="pslv"] a').first().evaluate(el=>el.focus({preventScroll:true}));await page.mouse.move(0,0);
  await page.clock.runFor(15000);assert.equal(await selected(),'0','Explicit pause survives focus and hover exits');
  await reel.locator('[data-reel-next]').click();
  await page.locator('[data-program="pslv"] a').first().evaluate(el=>el.focus({preventScroll:true}));await page.mouse.move(0,0);
  await page.clock.runFor(15000);assert.equal(await selected(),'1','Navigation preserves explicit pause');
  await reel.locator('[data-reel-toggle]').click();
  await page.locator('[data-program="pslv"] a').first().evaluate(el=>el.focus({preventScroll:true}));await page.mouse.move(0,0);
  await page.clock.runFor(7001);assert.equal(await selected(),'2');
  await reel.hover();await page.clock.runFor(15000);assert.equal(await selected(),'2','Hover pauses autoplay');
  await page.mouse.move(0,0);
  await page.evaluate(()=>{Object.defineProperty(document,'hidden',{value:true,configurable:true});document.dispatchEvent(new Event('visibilitychange'));});
  await page.clock.runFor(15000);assert.equal(await selected(),'2','Hidden tab pauses autoplay');
  await page.evaluate(()=>{Object.defineProperty(document,'hidden',{value:false,configurable:true});document.dispatchEvent(new Event('visibilitychange'));});
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.waitForFunction(()=>!document.querySelector('[data-reel-play]').hidden);
  await page.clock.runFor(15000);assert.equal(await selected(),'2');
  await reel.dispatchEvent('pointerdown',{clientX:200,clientY:100,pointerType:'touch'});
  await reel.dispatchEvent('pointerup',{clientX:80,clientY:105,pointerType:'touch'});assert.equal(await selected(),'3','Swipe changes photo');
  await reel.locator('[data-reel-slide="3"] .reel-image').dispatchEvent('click');
  assert.ok(page.url().endsWith('index.html'),'Completing a swipe must not follow the image link');
  assert.ok(Math.abs((await reel.boundingBox()).height-firstBox.height)<1,'Reel keeps stable dimensions');
  assert.equal(await reel.locator('[data-reel-slide="3"] a').first().getAttribute('href'),'gallery.html#nura-aug-2025','Airframe photograph links to its actual NURA event');
  await page.reload();await reel.scrollIntoViewIfNeeded();await page.waitForTimeout(100);await page.mouse.move(0,0);
  await page.clock.runFor(15000);assert.equal(await selected(),'0','Reduced-motion reload starts paused');
  await page.emulateMedia({reducedMotion:'no-preference'});
  await page.clock.runFor(15000);assert.equal(await selected(),'0','Preference change preserves paused state');
  await reel.locator('[data-reel-toggle]').click();await page.locator('[data-program="pslv"] a').first().evaluate(el=>el.focus({preventScroll:true}));await page.mouse.move(0,0);
  await page.clock.runFor(7001);assert.equal(await selected(),'1','Explicit play can resume the reel');
  await page.locator('footer').scrollIntoViewIfNeeded();await page.waitForTimeout(100);const offscreen=await selected();
  await page.clock.runFor(15000);assert.equal(await selected(),offscreen,'Offscreen reel remains still');
  await context.close();
  const plain=await browser.newContext({javaScriptEnabled:false});const p=await plain.newPage();await p.goto(`${base}/${locale}index.html`);
  const photo=p.locator('[data-reel-slide="0"]');assert.ok(await photo.isVisible());assert.ok(await photo.locator('a').first().getAttribute('href'));assert.ok(await photo.locator('figcaption').textContent());assert.equal(await p.locator('[data-reel-controls]').isVisible(),false);await plain.close();
 }
 console.log('PASS: bilingual reel timer, navigation, pause, focus, hover, hidden tab, reduced motion, swipe, dimensions and no-JS');
}
if(require.main===module)(async()=>{const browser=await chromium.launch({channel:process.env.PSI_BROWSER_CHANNEL||undefined,headless:true});try{await checkReel(browser);}finally{await browser.close();}})().catch(e=>{console.error(e);process.exitCode=1;});
module.exports={checkReel};
